#!/bin/sh
# Prints build_info.mbt: the version, the commit and the MoonBit toolchain this
# build is made from. prebuild.py runs it before every native build and
# rewrites build_info.mbt when the output differs, so a new commit, a new
# toolchain or a change to the variables below reaches the next build. moon
# also runs it (see moon.pkg) when build_info.mbt is missing, as for a
# wasm-gc build in a fresh checkout.
#
# SMOCK_VERSION overrides the version (default 0.0.0-dev).
# SMOCK_COMMIT overrides the commit (default: the checked-out commit).
set -eu

root=$(dirname "$0")/..
version=${SMOCK_VERSION:-0.0.0-dev}
commit=${SMOCK_COMMIT:-$(git -C "$root" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)}
moonc_version=$(moonc -v 2>/dev/null | cut -d' ' -f1)
toolchain="moonc ${moonc_version:-unknown}"

# The values become MoonBit string literals, so only plain characters pass.
for value in "$version" "$commit" "$toolchain"; do
  case $value in
  '' | *[!A-Za-z0-9.+_\ -]*)
    echo "gen_build_info.sh: unsupported characters in \"$value\"" >&2
    exit 1
    ;;
  esac
done

cat <<MBT
// Generated by gen_build_info.sh. Do not edit.

///|
let build_version : String = "$version"

///|
let build_commit : String = "$commit"

///|
let build_toolchain : String = "$toolchain"
MBT
